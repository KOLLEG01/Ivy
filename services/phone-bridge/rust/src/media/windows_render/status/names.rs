pub(super) fn encoding(value: u16) -> String {
    ENCODINGS
        .binary_search_by_key(&value, |x| x.0)
        .map(|i| ENCODINGS[i].1.to_owned())
        .unwrap_or_else(|_| value.to_string())
}
pub(super) fn subtype(value: u128) -> String {
    SUBTYPES
        .iter()
        .find(|x| x.0 == value)
        .map(|x| x.1.to_owned())
        .unwrap_or_else(|| {
            format!(
                "{:08x}-{:04x}-{:04x}-{:04x}-{:012x}",
                value >> 96,
                (value >> 80) & 0xffff,
                (value >> 64) & 0xffff,
                (value >> 48) & 0xffff,
                value & 0xffffffffffff
            )
        })
}

import test from 'node:test';
import assert from 'node:assert/strict';
import { DatabaseSync } from 'node:sqlite';
import { mkdtempSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { HiveStore } from '../services/hive/src/store.js';
import { openHiveStorage, reclaimStoragePages } from '../services/hive/src/storage-compaction.js';

test('legacy database compaction waits for space, resumes and preserves retained contents', t => {
  const root = mkdtempSync(join(tmpdir(), 'ivy-hive-compaction-'));
  const filename = join(root, 'legacy.sqlite');
  let db = new DatabaseSync(filename);
  t.after(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
  db.exec('PRAGMA journal_mode=WAL; CREATE TABLE payloads(id INTEGER PRIMARY KEY, body BLOB);');
  for (let i = 0; i < 12; i++) db.prepare('INSERT INTO payloads VALUES (?,zeroblob(1048576))').run(i);
  db.exec('DELETE FROM payloads WHERE id>=3; PRAGMA wal_checkpoint(TRUNCATE);');
  const before = statSync(filename).size;
  db.close();
  const waiting = openHiveStorage(filename, {}, () => 0);
  db = waiting.db;
  assert.match(waiting.pending!, /waiting/);
  assert.equal(db.prepare('PRAGMA auto_vacuum').get()!['auto_vacuum'], 0);
  assert.equal(statSync(filename).size, before);
  db.prepare('INSERT INTO payloads VALUES (?,?)').run(99, Buffer.from('Work continues below the reserve.'));
  assert.equal(db.prepare('SELECT CAST(body AS TEXT) AS body FROM payloads WHERE id=99').get()!['body'], 'Work continues below the reserve.');
  db.exec('DELETE FROM payloads WHERE id=99;');
  db.close();
  writeFileSync(filename + '.compacting', 'interrupted unfinished copy');
  const converted = openHiveStorage(filename, {}, () => Infinity);
  db = converted.db;
  assert.equal(converted.pending, null);
  assert.equal(db.prepare('PRAGMA auto_vacuum').get()!['auto_vacuum'], 2);
  assert.equal(db.prepare('SELECT COUNT(*) AS n FROM payloads').get()!['n'], 3);
  assert.equal(db.prepare('PRAGMA quick_check').get()!['quick_check'], 'ok');
  assert.ok(statSync(filename).size < before / 2);
  const compacted = statSync(filename).size;
  db.close();
  const repeated = openHiveStorage(filename, {}, () => 0);
  db = repeated.db;
  assert.equal(repeated.pending, null);
  assert.equal(statSync(filename).size, compacted, 'a completed conversion must not rewrite the database again');
  db.exec('DELETE FROM payloads;');
  reclaimStoragePages(db);
  assert.ok(statSync(filename).size < compacted / 2, 'normal retention must return freed pages to the filesystem');
});

test('fresh and upgraded Hive databases preserve their schema, epoch and data during page-map conversion', t => {
  const root = mkdtempSync(join(tmpdir(), 'ivy-hive-page-map-'));
  const filename = join(root, 'hive.sqlite');
  let store = new HiveStore(filename);
  t.after(() => { store.close(); rmSync(root, { recursive: true, force: true }); });
  assert.equal(store.get('PRAGMA auto_vacuum')!['auto_vacuum'], 2);
  assert.equal(store.metadata('storage_compaction_pending'), '');
  assert.equal(store.get('PRAGMA foreign_key_check'), undefined);
  const epoch = store.runtimeEpoch;
  store.setMetadata('compaction-test-data', 'retained');
  store.db.exec('PRAGMA auto_vacuum=NONE; VACUUM;');
  assert.equal(store.get('PRAGMA auto_vacuum')!['auto_vacuum'], 0);
  store.close();
  store = new HiveStore(filename);
  assert.equal(store.get('PRAGMA auto_vacuum')!['auto_vacuum'], 2);
  assert.equal(store.runtimeEpoch, epoch);
  assert.equal(store.metadata('compaction-test-data'), 'retained');
  assert.equal(store.metadata('storage_compaction_pending'), '');
  assert.equal(store.get('PRAGMA quick_check')!['quick_check'], 'ok');
});

import test from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { mkdtempSync, rmSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { DatabaseSync } from 'node:sqlite';
import { readDesktopVoiceCandidates } from '../tools/operations/phone-voice-archive.js';

test('Desktop archive inventory requires positive Voice source and includes native descendant scope', t => {
  const root = mkdtempSync(join(tmpdir(), 'ivy-voice-inventory-')), path = join(root, 'state.sqlite');
  const db = new DatabaseSync(path); t.after(() => { db.close(); rmSync(root, { recursive: true, force: true }); });
  db.exec('CREATE TABLE threads(id TEXT PRIMARY KEY,archived INTEGER,thread_source TEXT,title TEXT,recency_at_ms INTEGER); CREATE TABLE thread_spawn_edges(parent_thread_id TEXT,child_thread_id TEXT);');
  const add = db.prepare('INSERT INTO threads VALUES(?,?,?,?,?)'), voice = randomUUID(), child = randomUUID(), ordinary = randomUUID();
  add.run(voice, 0, 'voice_chat', 'Unrelated title', 3); add.run(child, 1, 'voice_chat', 'Archived child', 2);
  add.run(ordinary, 0, null, 'Voice chat', 1);
  db.prepare('INSERT INTO thread_spawn_edges VALUES(?,?)').run(voice, child);
  assert.deepEqual(readDesktopVoiceCandidates(path), [{ threadId: voice, descendantIds: [child] }]);
  assert.equal(db.prepare('SELECT archived FROM threads WHERE id=?').get(voice)?.['archived'], 0, 'classification never archives');
  db.prepare('UPDATE threads SET thread_source=NULL WHERE id=?').run(child);
  assert.throws(() => readDesktopVoiceCandidates(path), { code: 'phone_archive_scope_conflict' });
  db.prepare('DELETE FROM threads WHERE id=?').run(child);
  assert.throws(() => readDesktopVoiceCandidates(path), { code: 'phone_archive_scope_conflict' });
  db.exec('DELETE FROM thread_spawn_edges');
  db.prepare('INSERT INTO thread_spawn_edges VALUES(?,?)').run(voice, voice);
  assert.throws(() => readDesktopVoiceCandidates(path), { code: 'phone_archive_identity_invalid' });
  db.exec('DELETE FROM thread_spawn_edges');
  for (let index = 0; index < 256; index++) add.run(randomUUID(), 0, 'voice_chat', 'Bounded candidate', index);
  assert.throws(() => readDesktopVoiceCandidates(path), { code: 'phone_archive_capacity' });
  db.exec('ALTER TABLE threads RENAME COLUMN thread_source TO unknown_source');
  assert.throws(() => readDesktopVoiceCandidates(path), { code: 'phone_archive_schema_changed' });
});
